#include <stdio.h>
#include <stdlib.h>

int main()
{
    printf("Перевірка ідентифікації користувача:\n");
    printf("====================================\n");

    // Виклик whoami для отримання імені поточного користувача
    printf("Команда 'whoami': ");
    fflush(stdout); // Забезпечуємо вивід тексту перед результатом команди
    system("whoami");

    printf("\nДетальна інформація про обліковий запис:\n");
    printf("------------------------------------\n");

    // Виклик id для отримання UID, GID та списку груп
    system("id");

    printf("====================================\n");
    printf("Аналіз завершено.\n");

    return EXIT_SUCCESS;
}