#include <stdio.h>
#include <stdlib.h>
#include <unistd.h>

int main()
{
    printf("Спроба отримати доступ до /etc/shadow від імені адміністратора...\n");
    printf("-----------------------------------------------------------\n");

    // Використовуємо sudo для виконання команди від імені root.
    // Конфігурація системи має дозволяти поточному користувачу використовувати sudo.
    int result = system("sudo cat /etc/shadow");

    if (result == -1)
    {
        perror("Помилка при спробі виконати команду");
        return EXIT_FAILURE;
    }

    printf("-----------------------------------------------------------\n");
    if (result == 0)
    {
        printf("Результат: Доступ отримано успішно.\n");
    }
    else
    {
        printf("Результат: Відмовлено у доступі або команду скасовано.\n");
    }

    return EXIT_SUCCESS;
}